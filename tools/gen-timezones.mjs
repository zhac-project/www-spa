// Regenerates src/tzdata.js, the IANA name -> POSIX TZ string table behind
// Settings > Time. Run it when tzdata changes, on a machine with a current one:
//   node tools/gen-timezones.mjs [/usr/share/zoneinfo]
//
// The POSIX string is the footer line zic writes at the end of every TZif
// file -- the method of nayarsystems/posix_tz_db, whose own zones.csv is
// older than renames such as Europe/Kyiv and later rule changes. Zones:
// zone.tab (one per country and region, the names people look for), Etc/UTC
// and the fixed offsets Etc/GMT-14 .. Etc/GMT+12.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = process.argv[2] || "/usr/share/zoneinfo";
const version = readFileSync(join(dir, "tzdata.zi"), "utf8").match(/^# version (\S+)/)?.[1];
if (!version) throw new Error(`${dir}/tzdata.zi: no version line`);

const names = readFileSync(join(dir, "zone.tab"), "utf8").split("\n")
    .filter((l) => l && !l.startsWith("#"))
    .map((l) => l.split("\t")[2]);
names.push("Etc/UTC");
for (let h = -14; h <= 12; h++) if (h) names.push(`Etc/GMT${h > 0 ? "+" : ""}${h}`);

const lines = [...new Set(names)].sort().map((name) => {
    const tzif = readFileSync(join(dir, name)).toString("latin1");
    const posix = tzif.startsWith("TZif") ? tzif.trimEnd().split("\n").pop() : "";
    // A POSIX TZ string is printable ASCII without spaces; anything else means
    // a version-1 file (no footer) or a zone zic could not express in POSIX.
    if (!/^[\x21-\x7e]+$/.test(posix)) throw new Error(`${name}: no POSIX footer`);
    return `    ${JSON.stringify(name)}: ${JSON.stringify(posix)},`;
});

const out = `// SPDX-FileCopyrightText: 2025-2026 Evgenij Cjura and project contributors
// SPDX-License-Identifier: AGPL-3.0-or-later
// GENERATED by tools/gen-timezones.mjs -- do not edit by hand.
// IANA time zone -> POSIX TZ string, read from the IANA tz database ${version}
// (public domain, https://www.iana.org/time-zones).
export const TZDATA_VERSION = ${JSON.stringify(version)};

export const ZONES = {
${lines.join("\n")}
};
`;
const target = join(dirname(fileURLToPath(import.meta.url)), "../src/tzdata.js");
writeFileSync(target, out);
console.log(`src/tzdata.js: ${lines.length} zones, tzdata ${version}`);
